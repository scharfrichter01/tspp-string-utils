#ifndef STRING_UTILS_H
#define STRING_UTILS_H

#include <string>
#include <vector>

/**
 * @namespace StringUtils
 * @brief Пространство имен, содержащее утилиты для обработки строк.
 * 
 * Включает в себя функции для обрезки, разбиения, замены, 
 * проверки на палиндром, анаграмму и подсчета слов.
 */
namespace StringUtils {

    /**
     * @brief Удаляет пробельные символы в начале и в конце строки.
     * 
     * Пробельными символами считаются: пробел, табуляция (\t), 
     * новая строка (\n), возврат каретки (\r), вертикальная табуляция и подача страницы.
     * 
     * @param str Исходная строка для обработки.
     * @return std::string Новая строка без крайних пробельных символов.
     * @note Если строка состоит только из пробелов, вернется пустая строка.
     */
    std::string trim(const std::string& str);

    /**
     * @brief Разделяет строку на подстроки по указанному символу-разделителю.
     * 
     * @param str Исходная строка для разбиения.
     * @param delimiter Символ, который выступает в качестве разделителя.
     * @return std::vector<std::string> Вектор, содержащий полученные подстроки.
     * @note Два разделителя подряд приведут к появлению пустой строки в векторе.
     */
    std::vector<std::string> split(const std::string& str, char delimiter);

    /**
     * @brief Заменяет все вхождения одной подстроки на другую.
     * 
     * @param str Исходная строка.
     * @param from Подстрока, которую необходимо заменить.
     * @param to Подстрока, на которую будет произведена замена.
     * @return std::string Строка с выполненными заменами.
     * @note Замена является регистрозависимой (case-sensitive).
     * @throw std::invalid_argument Если подстрока `from` пустая, возвращается исходная строка.
     */
    std::string replace(const std::string& str, const std::string& from, const std::string& to);

    /**
     * @brief Проверяет, читается ли строка одинаково слева направо и справа налево.
     * 
     * @param str Проверяемая строка.
     * @return true Если строка является палиндромом.
     * @return false Если строка не является палиндромом.
     * @note Проверка учитывает регистр и пробелы (точное совпадение символов).
     */
    bool is_palindrome(const std::string& str);

    /**
     * @brief Проверяет, являются ли две строки анаграммами.
     * 
     * Анаграмма - это слово, полученное перестановкой букв другого слова.
     * 
     * @param str1 Первая строка.
     * @param str2 Вторая строка.
     * @return true Если строки состоят из одинакового набора символов.
     * @return false Если набор символов различается или длины строк не совпадают.
     * @note Проверка учитывает регистр символов.
     */
    bool is_anagram(const std::string& str1, const std::string& str2);

    /**
     * @brief Подсчитывает количество слов в строке.
     * 
     * Словом считается последовательность непробельных символов, 
     * разделенная одним или несколькими пробельными символами.
     * 
     * @param str Исходная строка.
     * @return int Количество найденных слов.
     */
    int word_count(const std::string& str);

} // namespace StringUtils

#endif // STRING_UTILS_H